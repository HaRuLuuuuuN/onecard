export const getCardById = (id: string): Card | undefined =>
  cards.find((c) => c.id === id);

export const getCardsByColor = (color: string): Card[] =>
  cards.filter((c) => c.color.includes(color as Card['color'][0]));

export const getCardsByType = (type: string): Card[] =>
  cards.filter((c) => c.type === type);

export const searchCards = (query: string): Card[] => {
  const q = query.toLowerCase();
  return cards.filter(
    (c) =>
      c.name.toLowerCase().includes(q) ||
      c.nameJa.includes(q) ||
      c.id.toLowerCase().includes(q) ||
      c.affiliations.some((a) => a.toLowerCase().includes(q))
  );
};
